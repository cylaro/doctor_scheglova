function symptomReason(sleep, body) {
  const parts = [];
  if (sleep === 'sleep_strong') parts.push('Изменения сна или настроения мешают вашей обычной жизни.');
  else if (sleep === 'sleep_mild') parts.push('Вы замечаете небольшие изменения сна или настроения.');
  if (body === 'body_strong') parts.push('Телесные симптомы заметно беспокоят вас.');
  else if (body === 'body_mild') parts.push('Некоторые телесные симптомы возникают время от времени.');
  if (!parts.length) return sleep === 'sleep_unsure' || body === 'body_unsure'
    ? 'Вы не уверены в части симптомов. Это не считается признаком заболевания.'
    : 'Вы не отметили заметных изменений сна, настроения или перечисленных телесных симптомов.';
  return parts.join(' ');
}

function labReason(labs) {
  if (labs === 'labs_changed') return 'Изменения в анализах нужно оценивать вместе с циклом, симптомами и принимаемыми препаратами. Они не определяют этап в этом опросе.';
  if (labs === 'labs_normal') return 'Результаты без отмеченных отклонений сами по себе не исключают менопаузальный переход.';
  if (labs === 'labs_unsure') return 'Неизвестный результат анализа не означает отклонение. При необходимости врач поможет его оценить.';
  return 'Отсутствие анализов не мешает обсудить симптомы с врачом. Необходимость обследований определяют на приеме.';
}

export function getResult(answers) {
  if (!Array.isArray(answers) || answers.length !== questions.length ||
      questions.some((question, index) => !question.options.some(option => option.id === answers[index]))) {
    throw new TypeError('Для результата нужен один допустимый ответ на каждый из пяти вопросов.');
  }

  const [age, cycle, sleep, body, labs] = answers;
  const strongSymptoms = sleep === 'sleep_strong' || body === 'body_strong';
  let key = 'reproductive';
  if (cycle === 'context' || (age !== '45plus' && cycle !== 'regular') ||
      (cycle === 'regular' && strongSymptoms)) key = 'uncertain';
  else if (age === '45plus' && cycle === 'absent12') key = 'postmenopause';
  else if (age === '45plus' && cycle !== 'regular') key = 'perimenopause';

  const copy = {
    reproductive: {
      title: 'Явных признаков перехода недостаточно',
      summary: 'По вашим ответам нельзя уверенно говорить о менопаузальном переходе. Привычный цикл не исключает ранних изменений, а самочувствие важно оценивать отдельно.',
    },
    perimenopause: {
      title: 'Изменения могут соответствовать перименопаузе',
      summary: 'После 45 лет изменения цикла могут быть связаны с менопаузальным переходом. У них бывают и другие причины — их помогает оценить врач.',
    },
    postmenopause: {
      title: 'Ответы могут соответствовать постменопаузе',
      summary: 'Вы отметили возраст от 45 лет и не менее 12 месяцев без менструаций. Если нет других причин их отсутствия, это может соответствовать естественной менопаузе.',
    },
    uncertain: {
      title: 'Для вывода нужна индивидуальная оценка',
      summary: cycle === 'context'
        ? 'В ваших обстоятельствах цикл не дает надежного ориентира. Врач учтет препараты, медицинскую историю и симптомы.'
        : age !== '45plus' && cycle !== 'regular'
          ? 'До 45 лет изменения или отсутствие менструаций важно обсудить с гинекологом. Этот опрос не может установить их причину.'
          : 'При привычном цикле выраженные симптомы не позволяют определить этап. Стоит обсудить их с врачом и разобраться в возможных причинах.',
    },
  };

  const baseStage = stages.find(stage => stage.key === key);
  const steps = baseStage ? baseStage.steps.map(step => ({ ...step })) : [
    { title: 'Запишитесь к гинекологу', text: 'Обсудите изменения цикла и самочувствия. Не начинайте гормональное лечение по результату опроса.' },
    { title: 'Подготовьтесь к приему', text: 'Запишите даты менструаций, симптомы, принимаемые препараты и перенесенные операции. Возьмите уже имеющиеся анализы.' },
    { title: 'Уточните необходимость обследований', text: 'Врач определит, нужны ли анализы и какие причины симптомов стоит проверить.' },
  ];

  if (sleep === 'sleep_strong' || body === 'body_strong') {
    steps[1] = {
      title: 'Обсудите симптомы, которые мешают',
      text: sleep === 'sleep_strong' && body === 'body_strong'
        ? 'Расскажите врачу о сне, настроении и телесном дискомфорте. Помощь можно подобрать, даже если этап пока неясен.'
        : sleep === 'sleep_strong'
          ? 'Расскажите врачу, как изменились сон и настроение и насколько это мешает жизни. У этих симптомов могут быть разные причины.'
          : 'Расскажите врачу о приливах, потливости или интимном дискомфорте: как часто они возникают и насколько мешают.',
    };
  } else if (labs === 'labs_changed' || labs === 'labs_unsure') {
    steps[1] = { title: 'Возьмите результаты на прием', text: 'Сохраните анализы вместе с датами сдачи и списком препаратов. Оценивать отдельную цифру без контекста недостаточно.' };
  }

  return {
    key,
    ...copy[key],
    reasons: [cycleReasons[cycle], symptomReason(sleep, body), labReason(labs)],
    steps,
    note: commonNote,
  };
}
